-- Turns the raw prototype copy made by scripts/recipe_graph.lua into the production graph used for
-- pricing (ADR-0002). Pure Lua: input and output are plain tables.
--
-- Raw input:
--   recipes     = { {name, energy, categories, hidden, parameter, enabled, unlocked,
--                    ingredients = {Amount...}, products = {Amount...}} ... }
--   mined       = { {name, kind, mining_time, products = {Amount...}, required_fluid, fluid_amount} ... }
--   tile_fluids = { [fluid_name] = true }
--   launches    = { {item, products = {Amount...}, part, parts} ... }: what launching `item` in a rocket
--                 of `parts` × `part` yields
--   keys        = sorted array of every item and fluid key that should have a value
--   Amount      = {type = "item"|"fluid", name, amount | amount_min + amount_max,
--                  independent_probability, shared_probability = {min, max}, extra_count_fraction}
--
-- Output:
--   recipes  = sorted array of {name, cost, inputs = {[key] = n}, outputs = {[key] = n}}, where a key is
--              "item/<name>" or "fluid/<name>", amounts are expected net amounts per craft and cost is
--              the fixed credit cost of one craft (crafting time, or mining time for sources)
--   fallback = same shape: planet-bound processes (a recipe that is recycling plus another category,
--              like Fulgora's scrap recycling) and the tile fluids that are not primary, which may
--              only price what the main graph does not
--   natural  = same shape: natural sources (trees, rocks, fish, plants, asteroid chunks), which may
--              only price what neither the main graph nor the fallback does
--   excluded = { [recipe_name] = reason }
--   keys     = raw.keys, passed through for the valuation
local recipe_graph = {}

-- Credits per second of crafting time (recipe energy at crafting speed 1).
recipe_graph.TIME_COST = 0.1
-- Credits per second of mining time, for resources and natural sources.
recipe_graph.MINING_COST = 1
-- Credits per unit of fluid pumped from a tile (water, lava...).
recipe_graph.TILE_FLUID_COST = 0.001
-- Tile fluids pumped everywhere: their pump is part of the main graph. Other tile fluids (lava, a
-- heavy-oil sea) belong to one place and are fallback sources.
recipe_graph.PRIMARY_TILE_FLUIDS = { water = true }
-- The game counts a resource's fluid_amount per 10 mining operations (uranium ore: 10 sulfuric acid
-- per 10 ore, https://wiki.factorio.com/Uranium_ore), although the API describes it per operation.
local MINING_OPERATIONS_PER_FLUID_AMOUNT = 10

-- Entity kinds whose mining yields raw materials from the world, not a placed building back.
local NATURAL_SOURCES = { tree = true, ["simple-entity"] = true, fish = true, plant = true,
  ["asteroid-chunk"] = true }

function recipe_graph.key(amount)
  return amount.type .. "/" .. amount.name
end

--- Expected amount of one product per craft: base amount (or the mean of the range), plus the extra
--- count fraction, times the chance it is given (independent probability times shared range).
function recipe_graph.expected_amount(product)
  local base = product.amount or (product.amount_min + math.max(product.amount_min, product.amount_max)) / 2
  local chance = product.independent_probability or 1
  local shared = product.shared_probability
  if shared then chance = chance * (shared.max - shared.min) end
  return (base + (product.extra_count_fraction or 0)) * chance
end

local function sum_into(totals, entries, measure)
  for _, entry in ipairs(entries) do
    local key = recipe_graph.key(entry)
    totals[key] = (totals[key] or 0) + measure(entry)
  end
  return totals
end

local function ingredient_amount(ingredient) return ingredient.amount end

--- Removes what a recipe gives back of its own inputs (catalysts), so only net flows remain.
local function net(inputs, outputs)
  for key, input in pairs(inputs) do
    local output = outputs[key]
    if output then
      local shared = math.min(input, output)
      inputs[key] = input - shared
      outputs[key] = output - shared
    end
  end
  for _, side in ipairs({ inputs, outputs }) do
    local empty = {}
    for key, amount in pairs(side) do
      if amount <= 0 then empty[#empty + 1] = key end
    end
    for _, key in ipairs(empty) do side[key] = nil end
  end
end

local function has_category(recipe, category)
  for _, name in ipairs(recipe.categories or {}) do
    if name == category then return true end
  end
  return false
end

-- Recycling recipes generated by the recycler mod have exactly this one category.
local function is_generated_recycling(recipe)
  return has_category(recipe, "recycling") and #recipe.categories == 1
end

local function exclusion_reason(recipe)
  if is_generated_recycling(recipe) then return "recycling" end
  if recipe.parameter then return "parameter" end
  if recipe.hidden then return "hidden" end
  if not (recipe.enabled or recipe.unlocked) then return "unreachable" end
  return nil
end

local function crafting_recipe(recipe)
  local inputs = sum_into({}, recipe.ingredients, ingredient_amount)
  local outputs = sum_into({}, recipe.products, recipe_graph.expected_amount)
  net(inputs, outputs)
  return { name = recipe.name, cost = recipe.energy * recipe_graph.TIME_COST, inputs = inputs, outputs = outputs }
end

local function mining_recipe(source)
  local inputs = {}
  if source.required_fluid and (source.fluid_amount or 0) > 0 then
    inputs["fluid/" .. source.required_fluid] = source.fluid_amount / MINING_OPERATIONS_PER_FLUID_AMOUNT
  end
  local outputs = sum_into({}, source.products, recipe_graph.expected_amount)
  net(inputs, outputs)
  return { name = "mine/" .. source.name, cost = source.mining_time * recipe_graph.MINING_COST,
    inputs = inputs, outputs = outputs }
end

local function by_name(a, b) return a.name < b.name end

--- Builds the production graph from the raw prototype copy.
function recipe_graph.build(raw)
  local recipes, fallback, natural, excluded = {}, {}, {}, {}
  for _, recipe in ipairs(raw.recipes) do
    local reason = exclusion_reason(recipe)
    local built = not reason and crafting_recipe(recipe)
    if built and next(built.outputs) == nil then reason = "no-net-output" end
    if reason then
      excluded[recipe.name] = reason
    elseif has_category(recipe, "recycling") then
      fallback[#fallback + 1] = built
    else
      recipes[#recipes + 1] = built
    end
  end
  for _, source in ipairs(raw.mined) do
    local list = source.kind == "resource" and recipes or NATURAL_SOURCES[source.kind] and natural
    local built = list and mining_recipe(source)
    if built and next(built.outputs) ~= nil then list[#list + 1] = built end
  end
  for _, launch in ipairs(raw.launches or {}) do
    recipes[#recipes + 1] = {
      name = "launch/" .. launch.item,
      cost = 0,
      inputs = { ["item/" .. launch.item] = 1, ["item/" .. launch.part] = launch.parts },
      outputs = sum_into({}, launch.products, recipe_graph.expected_amount),
    }
  end
  for fluid in pairs(raw.tile_fluids) do
    local pump = {
      name = "pump/" .. fluid, cost = recipe_graph.TILE_FLUID_COST, inputs = {}, outputs = { ["fluid/" .. fluid] = 1 },
    }
    local list = recipe_graph.PRIMARY_TILE_FLUIDS[fluid] and recipes or fallback
    list[#list + 1] = pump
  end
  table.sort(recipes, by_name)
  table.sort(fallback, by_name)
  table.sort(natural, by_name)
  return { recipes = recipes, fallback = fallback, natural = natural, excluded = excluded, keys = raw.keys }
end

return recipe_graph
