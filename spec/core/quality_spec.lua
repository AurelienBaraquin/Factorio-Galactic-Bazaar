local quality = require("scripts.core.quality")

describe("quality.value", function()
  it("is the normal value at level 0 and grows by the factor per level", function()
    assert.are.equal(4, quality.value(4, 0))
    assert.are.equal(4 * quality.FACTOR_PER_LEVEL ^ 2, quality.value(4, 2))
    assert.are.equal(4 * quality.FACTOR_PER_LEVEL ^ 5, quality.value(4, 5))
  end)
end)

describe("quality keys", function()
  it("keep the normal key for normal quality and round-trip the others", function()
    assert.are.equal("item/iron-plate", quality.key("item/iron-plate", "normal"))
    assert.are.equal("item/iron-plate", quality.key("item/iron-plate", nil))
    assert.are.equal("item/iron-plate@rare", quality.key("item/iron-plate", "rare"))
    assert.are.same({ "item/iron-plate", "rare" }, { quality.split("item/iron-plate@rare") })
    assert.are.same({ "item/iron-plate", "normal" }, { quality.split("item/iron-plate") })
  end)
end)
